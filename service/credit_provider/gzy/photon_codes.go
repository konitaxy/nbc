// PhotonCodeMessage 按 Photon 应答 code 返回中文说明；未收录时返回空字符串。
func PhotonCodeMessage(code string) string {
	return photonCodeMessages[strings.TrimSpace(strings.ToUpper(code))]
}

// PhotonCodeStatus 按 Photon 应答 code 返回状态：succeed / failed / pending / suspend。
func PhotonCodeStatus(code string) string {
	return photonCodeStatus[strings.TrimSpace(strings.ToUpper(code))]
}

func photonUserMessage(code, apiMsg string) string {
	code = strings.TrimSpace(strings.ToUpper(code))
	if mapped := photonCodeMessages[code]; mapped != "" {
		return mapped
	}
	if s := strings.TrimSpace(apiMsg); s != "" {
		return s
	}
	if code != "" {
		return "错误码 " + code
	}
	return "系统异常"
}
